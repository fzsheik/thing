// Generates one typed entry per plush pack in src/ and syncs package.json "exports"
// and src/entries.json. Run after adding a pack: `npm run gen`.
import { build } from "esbuild";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const components = "."; // import base, relative to src/
const tmp = path.join(root, ".gen/packs.mjs");

await build({entryPoints: [path.join(root, "src/plush/packs/index.ts")], bundle: true, format: "esm", outfile: tmp, logLevel: "error"});
const {plushPacks} = await import(pathToFileURL(tmp).href);
await rm(path.join(root, ".gen"), {recursive: true});

const header = '"use client";\n\n// Generated by scripts/gen-entries.mjs — do not edit.\n';
await mkdir(path.join(root, "src"), {recursive: true});

for (const p of plushPacks) {
  const name = p.component;
  const ids = p.characters.map(c => JSON.stringify(c.id)).join(" | ");
  await writeFile(path.join(root, "src", `${p.id}.tsx`), `${header}
import { PlushMascot, type PlushMascotProps } from "${components}/plush/plush-mascot.tsx";
import { ${p.id} } from "${components}/plush/packs/${p.id}.ts";

export type ${name}Character = ${ids};

export type ${name}Props = Omit<PlushMascotProps, "character"> & {
  /** Which character to render. */
  character?: ${name}Character;
};

/** ${p.name}: ${p.tagline} */
export function ${name}({character = ${JSON.stringify(p.characters[0].id)}, texture = ${JSON.stringify(p.texture)}, particleColor = ${JSON.stringify(p.particleColor)}, ...props}: ${name}Props) {
  const c = ${p.id}.characters.find(x => x.id === character) ?? ${p.id}.characters[0];
  return <PlushMascot character={c} texture={texture} particleColor={particleColor} {...props} />;
}

export default ${name};
export { ${p.id} as pack };
export { plushStates, textures, type PlushState, type Texture, type PlushPack, type PlushCharacter } from "${components}/plush/plush-kit.ts";
export type { PlushMascotProps };
`);
}

// Hand-written entries live next to the generated ones.
const entries = {space: "src/space.ts", fuzzy: "src/fuzzy.ts", plush: "src/plush.ts", motion: "src/motion.ts",
  ...Object.fromEntries(plushPacks.map(p => [p.id, `src/${p.id}.tsx`]))};
await writeFile(path.join(root, "src", "entries.json"), JSON.stringify(entries, null, 2) + "\n");

const pkgPath = path.join(root, "package.json");
const pkg = JSON.parse(await readFile(pkgPath, "utf8"));
pkg.exports = Object.fromEntries([
  ...Object.keys(entries).map(e => [`./${e}`, {types: `./dist/${e}.d.ts`, default: `./dist/${e}.js`}]),
  ["./package.json", "./package.json"],
]);
await writeFile(pkgPath, JSON.stringify(pkg, null, 2) + "\n");
console.log(`entries: ${Object.keys(entries).join(", ")}`);
